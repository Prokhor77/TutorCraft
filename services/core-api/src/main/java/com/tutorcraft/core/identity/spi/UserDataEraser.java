package com.tutorcraft.core.identity.spi;

import java.util.UUID;

/**
 * Модуль, хранящий данные пользователя. Используется полным удалением пользователя главным администратором
 * (FR-USER-05): каждая реализация удаляет персональные данные и учебные записи пользователя в своих таблицах.
 * <p>
 * Строки, где пользователь — автор действия над чужими данными (выставил оценку, создал ссылку, оплатил заказ,
 * групповая сдача), не удаляются: nullable-ссылки обнуляются, остальные продолжают указывать на обезличенную
 * запись users. Вызывается в одной транзакции; реализации зависят только от своих таблиц и должны быть идемпотентны.
 */
public interface UserDataEraser {

    void eraseUser(UUID tenantId, UUID userId);
}
