package com.tutorcraft.core.courses.spi;

import java.util.UUID;

/**
 * Модуль, хранящий данные, привязанные к курсу. Используется физической очисткой корзины (FR-COURSE-07, ADR-010):
 * курс удаляется, только если ни один владелец его не удерживает. Реализации зависят только от своих таблиц.
 */
public interface CourseDataOwner {

    /**
     * true — у курса есть данные учащихся или финансовые данные этого модуля (записи, сдачи, попытки, оценки, заказы,
     * прогресс), которые хранятся по требованиям закона/оценивания; такой курс остаётся в корзине (анонимизация — FR-USER-05, P1).
     */
    boolean retainsCourse(UUID tenantId, UUID courseId);

    /**
     * Удаляет служебные данные модуля по курсу (настройки, ссылки-приглашения и т.п.). Вызывается в транзакции физического
     * удаления курса и только после того, как ни один владелец не удержал курс.
     */
    default void purgeCourse(UUID tenantId, UUID courseId) {
    }
}
